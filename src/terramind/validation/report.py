"""Write docs/results.md and experiments/results.json from the collected numbers."""

from __future__ import annotations

import json
from pathlib import Path

from terramind.config import repo_root
from terramind.validation import results as res

M = res.MODALITIES


def _f(x, digits=3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def _ci(ci) -> str:
    return f"[{ci[0]:.3f}, {ci[1]:.3f}]"


def checks(r: dict) -> list[dict]:
    """Protocol checks from the specification; each is pass or fail, not a judgement."""
    seg = r["segmentation"]
    out = []

    def add(name, ok, detail):
        out.append({"check": name, "ok": bool(ok), "detail": detail})

    add(
        "3-5 seeds per segmentation model",
        len(seg) == 3 and all(3 <= b["seeds"] <= 5 for b in seg.values()),
        ", ".join(f"{M[m]} {b['seeds']}" for m, b in seg.items()),
    )
    add(
        "Leave-one-event-out covers every event for every input",
        all(len(t["events"]) == 11 for t in r["transfer"].values()) and len(r["transfer"]) == 3,
        ", ".join(f"{M[m]} {len(t['events'])}/11" for m, t in r["transfer"].items()),
    )
    add(
        "Non-learned baseline reported",
        bool(r["thresholds"]),
        ", ".join(r["thresholds"]) if r["thresholds"] else "missing",
    )
    add(
        "Calibration evaluated for every input",
        len(r["calibration"]) == 3,
        f"{len(r['calibration'])}/3 ensemble reports",
    )
    add(
        "Event-level confidence intervals on the test split",
        all("event_bootstrap" in b["splits"]["test"] for b in seg.values()),
        "bootstrap over 10 events",
    )
    add(
        "Event-level interval on the unseen region",
        False,
        "Bolivia is a single event, so no event-level interval can be formed",
    )
    add("RL uses at least 3 seeds", bool(r["e7"]) and all(
        p.get("seeds", 3) >= 3 for p in r["e7"]["results"]["test"]["policies"].values()
    ), "PPO and its ablation")  # fmt: skip
    add(
        "Simulated outcomes labelled as simulated",
        bool(r["e7"] and r["e8"]) and r["e7"]["simulated"] and r["e8"]["simulated"],
        "flag in both result files",
    )
    return out


def markdown(r: dict, claims: list[dict], protocol: list[dict]) -> str:
    seg = r["segmentation"]
    lines = [
        "# Results",
        "",
        "Generated by `terramind validate` from run files. Do not edit by hand.",
        "All simulation numbers are simulated outcomes, not field results.",
        "",
        "## Verdicts on the research questions",
        "",
        "| | Question | Verdict | Basis | Limits |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {c['rq']} | {c['question']} | **{c['verdict']}** | {c['basis']} | {c['limits']} |"
        for c in claims
    ]

    lines += [
        "",
        "## Flood mapping (water IoU)",
        "",
        "Seed std is training noise. The event interval resamples the 10 test events and is",
        "the honest uncertainty about performance on a new event.",
        "",
        (
            "| Input | Seeds | Test | Seed std | 95% interval over events | Mean over events | "
            "Worst test event | Bolivia (seed range) |"
        ),
        "|---|---|---|---|---|---|---|---|",
    ]
    for m, b in seg.items():
        t, bo = b["splits"]["test"], b["splits"]["bolivia"]
        lines.append(
            f"| {M[m]} | {b['seeds']} | {_f(t['iou_mean'])} | {_f(t['iou_seed_std'])} | "
            f"{_ci(t['event_bootstrap']['ci95'])} | {_f(t['macro_event_iou'])} | "
            f"{t['worst_event']['event']} {_f(t['worst_event']['iou'])} | "
            f"{_f(bo['iou_mean'])} ({_f(bo['iou_seed_range'][0])}-{_f(bo['iou_seed_range'][1])}) |"
        )
    if r["thresholds"]:
        for method, s in r["thresholds"].items():
            lines.append(
                f"| {method} (no learning) | - | {_f(s['test'])} | - | - | - | - | {_f(s['bolivia'])} |"
            )

    events = sorted(seg["s1"]["splits"]["test"]["per_event"])
    lines += ["", "### Per event, test split (mean of seeds)", "", "| Event | " + " | ".join(
        M[m] for m in seg) + " |", "|---|" + "---|" * len(seg)]  # fmt: skip
    for e in events:
        lines.append(
            f"| {e} | "
            + " | ".join(_f(seg[m]["splits"]["test"]["per_event"][e]["mean"]) for m in seg)
            + " |"
        )

    lines += [
        "",
        "## Calibration (5-seed ensemble, pixel level)",
        "",
        (
            "| Input | Split | ECE single | ECE ensemble | ECE after temperature | "
            "Error at 100% / 90% coverage |"
        ),
        "|---|---|---|---|---|---|",
    ]
    for m, c in r["calibration"].items():
        for split in ("test", "bolivia"):
            s = c["splits"][split]
            lines.append(
                f"| {M[m]} | {split} | {_f(s['ece_single'])} | {_f(s['ece_ensemble'])} | "
                f"{_f(s['ece_scaled'])} | {s['error_full']:.1%} / {s['error_90']:.1%} |"
            )

    lines += [
        "",
        "## Transfer: leave one event out (one seed per fold)",
        "",
        "| Input | Mean IoU drop when unseen | Worst drop | Events that got worse |",
        "|---|---|---|---|",
    ]
    for m, t in r["transfer"].items():
        lines.append(
            f"| {M[m]} | {t['mean_drop']:+.3f} | {t['worst_drop']:+.3f} | "
            f"{t['worse_count']} of {t['compared_events']} |"
        )

    if r["retrieval"]:
        lines += [
            "",
            (
                f"## Retrieval ({sum(r['retrieval']['cases'].values())} generated queries, "
                f"k = {r['retrieval']['k']})"
            ),
            "",
            "| Method | Precision | Recall | nDCG | In asked region |",
            "|---|---|---|---|---|",
        ]
        for name, m in r["retrieval"]["all"].items():
            lines.append(
                f"| {name} | {_f(m['precision'], 2)} | {_f(m['recall'], 2)} | {_f(m['ndcg'], 2)} | "
                f"{_f(m.get('spatial_ok'), 2)} |"
            )

    if r["e7"]:
        lines += [
            "",
            "## Simulated flood response (E7)",
            "",
            "| Policy | Test | 95% interval | Bolivia | 95% interval |",
            "|---|---|---|---|---|",
        ]
        t, b = (r["e7"]["results"][s]["policies"] for s in ("test", "bolivia"))
        for name in t:
            lines.append(
                f"| {name} | {_f(t[name]['auc'])} | {_ci(t[name]['auc_ci95'])} | "
                f"{_f(b[name]['auc'])} | {_ci(b[name]['auc_ci95'])} |"
            )

    if r.get("agents"):
        a = r["agents"]
        lines += [
            "",
            (
                f"## Question answering (RQ5), {len(a['questions'])} frozen questions "
                f"(fingerprint {a['fingerprint']})"
            ),
            "",
            (
                "| System | Accuracy | Answerable correct | Unanswerable refused | "
                "Answerable refused | Cites a supporting record | Unsupported decimals |"
            ),
            "|---|---|---|---|---|---|---|",
        ]
        for name, s in a["systems"].items():
            m = s["summary"]
            lines.append(
                f"| {name} | {_f(m['accuracy'], 2)} | {_f(m['answerable_correct'], 2)} | "
                f"{_f(m['unanswerable_refused'], 2)} | {_f(m['over_refusal'], 2)} | "
                f"{_f(m['grounded_when_answering'], 2)} | {_f(m['unsupported_decimal_rate'], 3)} |"
            )
        cats = list(next(iter(a["systems"].values()))["by_category"])
        lines += ["", "| System | " + " | ".join(cats) + " |", "|---|" + "---|" * len(cats)]
        for name, s in a["systems"].items():
            lines.append(
                f"| {name} | " + " | ".join(_f(s["by_category"][c], 2) for c in cats) + " |"
            )
        if a["paired_accuracy"]:
            lines += ["", "Paired accuracy differences (bootstrap over questions):", ""]
            lines += [
                f"- {k}: {v['mean']:+.3f} [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}]"
                for k, v in a["paired_accuracy"].items()
            ]

    if r["e8"]:
        settings = list(r["e8"]["settings"])
        lines += [
            "",
            "## Simulated chain ablation (E8), test split, difference to the radar ensemble",
            "",
            "| Planner is given | " + " | ".join(settings) + " |",
            "|---|" + "---|" * len(settings),
        ]
        for stage in r["e8"]["settings"][settings[0]]["splits"]["test"]["stages"]:
            cells = []
            for s in settings:
                m = r["e8"]["settings"][s]["splits"]["test"]["stages"][stage]
                lo, hi = m["vs_reference_ci95"]
                cells.append(f"{_f(m['auc'])} ({m['vs_reference']:+.3f} [{lo:+.3f}, {hi:+.3f}])")
            lines.append(f"| {stage} | " + " | ".join(cells) + " |")

    if r.get("e9"):
        e9 = r["e9"]
        lines += [
            "",
            "## Simulated dispatch with a cost for wasted deployments (E9)",
            "",
            "Utility = (flooded area served - cost x deployments to dry cells) / total flooded",
            "area. Cells show utility, the paired difference to the calibrated planner with its",
            "95% interval, and wasted deployments per episode.",
            "",
            "| Waste cost | Policy | Test | Bolivia |",
            "|---|---|---|---|",
        ]
        for cost, res_ in e9["settings"].items():
            for name in res_["splits"]["test"]["policies"]:
                cells = []
                for split in ("test", "bolivia"):
                    m = res_["splits"][split]["policies"][name]
                    lo, hi = m["vs_reference_ci95"]
                    cells.append(
                        f"{_f(m['utility'])} ({m['vs_reference']:+.3f} [{lo:+.3f}, {hi:+.3f}]), "
                        f"{m['wasted_deployments']:.1f} wasted"
                    )
                lines.append(f"| {cost} | {name} | " + " | ".join(cells) + " |")
        lines += [
            "",
            "Predicting dry cells (Brier score, lower is better):",
            "",
            "| Belief | Test | Bolivia |",
            "|---|---|---|",
        ]
        for name in e9["cell_skill"]["test"]:
            lines.append(
                f"| {name} | {_f(e9['cell_skill']['test'][name]['brier'], 4)} | "
                f"{_f(e9['cell_skill']['bolivia'][name]['brier'], 4)} |"
            )

    lines += ["", "## Protocol checks", "", "| Check | Result | Detail |", "|---|---|---|"]
    lines += [
        f"| {c['check']} | {'pass' if c['ok'] else 'FAIL'} | {c['detail']} |" for c in protocol
    ]
    return "\n".join(lines) + "\n"


def run(figures: bool = True) -> dict:
    r = res.collect()
    claims = res.claims(r)
    protocol = checks(r)
    out_json = repo_root() / "experiments" / "results.json"
    out_json.write_text(
        json.dumps({"results": r, "claims": claims, "checks": protocol}, indent=2), encoding="utf-8"
    )
    out_md = repo_root() / "docs" / "results.md"
    out_md.write_text(markdown(r, claims, protocol), encoding="utf-8")
    made: list[Path] = []
    if figures:
        from terramind.validation import figures as fig

        made = fig.build(r)
    return {
        "json": out_json,
        "markdown": out_md,
        "figures": made,
        "claims": claims,
        "checks": protocol,
    }
